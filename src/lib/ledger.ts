import { nextOccurrenceOnOrAfter } from "@/lib/recurrence";

// "investment" and "card_payment" are never user-selectable (not in
// ENTRY_KINDS below, not in the addEntry/updateEntry zod schema):
// - "investment" only ever exists on a row created server-side by
//   src/lib/actions/positions.ts alongside a portfolio_positions row, when
//   that purchase is marked as funded from cash.
// - "card_payment" only ever exists on a row created server-side by
//   src/lib/actions/credit-cards.ts's payCreditCardDebt, when the user
//   declares they paid (fully or partially) toward a specific card's debt.
//   It's a transfer (cash -> card debt), not spending — v_monthly_surplus's
//   income/expense CTEs only match kind='income'/'expense', so it never
//   inflates a month's spending total.
export type EntryKind = "income" | "expense" | "subscription" | "investment" | "card_payment";
export type EntryRecurrence = "none" | "weekly" | "monthly" | "yearly";

export type Entry = {
  id: string;
  kind: EntryKind;
  amount: number;
  currency: "TRY";
  category: string | null;
  description: string | null;
  recurrence: EntryRecurrence;
  next_due_date: string | null;
  occurred_at: string;
  // Which card this row concerns:
  // - kind='expense'/'subscription': null means cash/debit (reduces cash
  //   immediately, today's default behavior); set means charged to that
  //   card — a debt, not a cash event, until a card_payment pays it down
  //   (src/lib/cashflow.ts never counts these directly against the
  //   balance, only against creditCardDebtBalance).
  // - kind='card_payment': required — which card's debt this reduces.
  // Carried forward automatically when a card-imported expense is later
  // converted into a recurring subscription (updateEntry never touches this
  // field on its own row; its cascade to already-materialized future rows
  // does, see updateEntry), so materializeDueOccurrences
  // (src/lib/recurrence-materialize.ts) keeps tagging every future month's
  // row with the right card.
  credit_card_id: string | null;
  created_at: string;
  // Set only on a concrete row generated from a recurring template (see
  // src/lib/recurrence-materialize.ts) — null for both one-off entries and
  // for the template row itself.
  template_id: string | null;
  // Set only on an "investment" row — the portfolio position it funded
  // (src/lib/actions/positions.ts). Null for every other kind.
  portfolio_position_id: string | null;
  // Set only on a row generated by a taksit (installment) purchase — all
  // three null together, or all three set together (DB-enforced, see
  // entries_installment_fields_consistent in
  // supabase/migrations/20260721130000_installments_and_categories.sql).
  // Unlike template_id, every row in the series already exists the moment
  // the purchase is entered (src/lib/installments.ts) — there's no lazy
  // materialization to model.
  installment_group_id: string | null;
  installment_index: number | null;
  installment_count: number | null;
};

// Labels come from messages/{locale}.json ("ledger" namespace) — components
// resolve via useTranslations, keyed by these values. "investment" is
// deliberately excluded — see the EntryKind comment above. "subscription"
// is also excluded: a subscription is only ever created from the
// Abonelikler page's own FAB (defaultKind="subscription") or edited from
// its own list — QuickEntryForm hides its kind switcher entirely in that
// case (see there), so it never needs to appear as a choice here.
export const ENTRY_KINDS: EntryKind[] = ["expense", "income"];
export const ENTRY_RECURRENCES: EntryRecurrence[] = ["none", "weekly", "monthly", "yearly"];

// Preset category chips (docs/phase1-plan.md A.1 — entries.category). The
// stored value is always this Turkish token regardless of UI locale (it's a
// stable DB key, not display text) — components translate it for display
// via t(`ledger.category.${value}`).
export const ENTRY_CATEGORIES = [
  "maaş",
  "serbest",
  "kira",
  "fatura",
  "abonelik",
  "market",
  "yemek",
  "eğlence",
  "ulaşım",
  "diğer",
] as const;

export const DEFAULT_CATEGORY = "diğer";

type PresetCategory = (typeof ENTRY_CATEGORIES)[number];

export function isPresetCategory(value: string): value is PresetCategory {
  return (ENTRY_CATEGORIES as readonly string[]).includes(value);
}

// entry.category is always one of ENTRY_CATEGORIES in practice (the form
// only offers those as toggle chips) — this guards against legacy/unknown
// values so a missing message key never throws.
export function categoryLabel(t: (key: string) => string, category: string | null): string {
  const value = category ?? DEFAULT_CATEGORY;
  return isPresetCategory(value) ? t(`category.${value}`) : value;
}

export function toDateString(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

// The date worth showing for a row: for a recurring entry, that's its
// payment/due date — but next_due_date is an ANCHOR (any past, present, or
// future date establishing which day it recurs on), not necessarily the
// actual upcoming occurrence, so it's rolled forward the same way
// FixedItemsTimeline already does (nextOccurrenceOnOrAfter) rather than
// shown verbatim — a monthly anchor of "15 Temmuz" must still read as the
// (past) 15th having rolled into next month's 15th, not stay stuck on a
// date that's already gone by. occurred_at for a recurring row is just
// "when this was added to the ledger", not something the user chose, so
// showing it as *the* date read as "wrong" (it always looked like today).
// One-off entries have no next_due_date at all, so occurred_at (now a real,
// user-editable field) is the only meaningful date there.
//
// `from` matters: it's the reference point the occurrence rolls forward
// from. Defaulting to "today" is right for an unscoped view, but wrong when
// the caller is asking "what does this look like *in September*" — passing
// September 1st as `from` here is what makes a monthly bill actually show
// up as due in September instead of being stuck on whichever single month
// contains its next occurrence from today (see EntryTable's monthMatches).
export function entryDisplayDate(
  entry: Pick<Entry, "recurrence" | "next_due_date" | "occurred_at">,
  from: Date = new Date(),
): string {
  if (entry.recurrence !== "none" && entry.next_due_date) {
    const next = nextOccurrenceOnOrAfter(entry.next_due_date, entry.recurrence, from);
    if (next) return toDateString(next);
  }
  return entry.occurred_at;
}
